-- AI 결과 DB. 행은 쌓기만 하고(트리거), event_findings.user 는 예약어라 쿼리에서 "user" 로 감쌉니다.

CREATE FUNCTION deny() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0];
END $$;

-- --- 정책 관리 검토 · 서버 점검 ---

CREATE TABLE policy_reviews (
    id                  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source              TEXT    NOT NULL DEFAULT '',
    load_issues         TEXT    NOT NULL DEFAULT '[]',
    rules               TEXT    NOT NULL DEFAULT '[]',
    summary             TEXT    NOT NULL DEFAULT '',
    failed              INTEGER NOT NULL DEFAULT 0 CHECK (failed IN (0, 1)),
    error               TEXT,
    model               TEXT    NOT NULL,
    elapsed_sec         DOUBLE PRECISION,
    created_at          TEXT    NOT NULL,
    servers_source      TEXT    NOT NULL DEFAULT '',
    servers_load_issues TEXT    NOT NULL DEFAULT '[]'
);
CREATE TRIGGER policy_reviews_immutable BEFORE UPDATE ON policy_reviews
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');

CREATE TABLE policy_issues (
    id             BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id      BIGINT  NOT NULL REFERENCES policy_reviews (id),
    seq            INTEGER NOT NULL,
    kind           TEXT    NOT NULL,
    level          TEXT    NOT NULL CHECK (level IN ('정상', '주의', '위험')),
    policy_ids     TEXT    NOT NULL DEFAULT '[]',
    reason         TEXT    NOT NULL DEFAULT '',
    recommendation TEXT    NOT NULL DEFAULT '',
    UNIQUE (review_id, seq)
);
CREATE TRIGGER policy_issues_immutable BEFORE UPDATE ON policy_issues
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');

CREATE TABLE server_findings (
    id             BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id      BIGINT  NOT NULL REFERENCES policy_reviews (id),
    seq            INTEGER NOT NULL,
    host           TEXT    NOT NULL,
    ip             TEXT    NOT NULL DEFAULT '',
    state          TEXT    NOT NULL DEFAULT '{}',
    matched        TEXT    NOT NULL DEFAULT '',
    level          TEXT    CHECK (level IN ('정상', '주의', '위험')),
    reason         TEXT    NOT NULL DEFAULT '',
    recommendation TEXT    NOT NULL DEFAULT '',
    sources        TEXT    NOT NULL DEFAULT '[]',
    failed         INTEGER NOT NULL DEFAULT 0 CHECK (failed IN (0, 1)),
    error          TEXT,
    elapsed_sec    DOUBLE PRECISION,
    gaps           TEXT    NOT NULL DEFAULT '[]',
    unjudged       TEXT    NOT NULL DEFAULT '[]',
    snapshot       TEXT    NOT NULL DEFAULT '{}',
    UNIQUE (review_id, seq),
    CHECK (failed = 1 OR level IS NOT NULL)
);
CREATE INDEX server_findings_host ON server_findings (host, review_id);
CREATE TRIGGER server_findings_immutable BEFORE UPDATE ON server_findings
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');

-- --- 로그 감시 ---

CREATE TABLE monitor_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source        TEXT   NOT NULL DEFAULT '',
    load_issues   TEXT   NOT NULL DEFAULT '[]',
    since         TEXT,
    until         TEXT,
    last_event_at TEXT,
    model         TEXT   NOT NULL,
    created_at    TEXT   NOT NULL,
    stage         TEXT   NOT NULL DEFAULT 'final' CHECK (stage IN ('final', 'fast'))
);
CREATE INDEX monitor_runs_stage ON monitor_runs (stage, last_event_at);
CREATE TRIGGER monitor_runs_immutable BEFORE UPDATE ON monitor_runs
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');

CREATE TABLE event_findings (
    id             BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         BIGINT  NOT NULL REFERENCES monitor_runs (id),
    "user"         TEXT    NOT NULL,
    subject        TEXT    NOT NULL DEFAULT '',
    first_event_at TEXT    NOT NULL,
    last_event_at  TEXT    NOT NULL,
    events         TEXT    NOT NULL,
    level          TEXT    CHECK (level IN ('정상', '주의', '위험')),
    reason         TEXT    NOT NULL DEFAULT '',
    recommendation TEXT    NOT NULL DEFAULT '',
    sources        TEXT    NOT NULL DEFAULT '[]',
    failed         INTEGER NOT NULL DEFAULT 0 CHECK (failed IN (0, 1)),
    error          TEXT,
    elapsed_sec    DOUBLE PRECISION,
    CHECK (failed = 1 OR level IS NOT NULL)
);
CREATE INDEX event_findings_run ON event_findings (run_id);
CREATE INDEX event_findings_user ON event_findings ("user", last_event_at);
CREATE TRIGGER event_findings_immutable BEFORE UPDATE ON event_findings
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');

-- --- 질의 기록 ---

CREATE TABLE qa_records (
    id               BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind             TEXT    NOT NULL CHECK (kind IN ('policy', 'logs', 'servers')),
    question         TEXT    NOT NULL,
    answer           TEXT    NOT NULL DEFAULT '',
    sources          TEXT    NOT NULL DEFAULT '[]',
    criteria         TEXT    NOT NULL DEFAULT '{}',
    facts            TEXT,
    evidence         TEXT    NOT NULL DEFAULT '[]',
    failed           INTEGER NOT NULL DEFAULT 0 CHECK (failed IN (0, 1)),
    error            TEXT,
    model            TEXT    NOT NULL,
    elapsed_sec      DOUBLE PRECISION,
    asker_id         BIGINT  NOT NULL,
    asker_name       TEXT    NOT NULL,
    asker_department TEXT    NOT NULL DEFAULT '',
    asked_at         TEXT    NOT NULL
);
CREATE INDEX qa_records_asker ON qa_records (asker_id, kind, asked_at);
CREATE TRIGGER qa_records_immutable BEFORE UPDATE ON qa_records
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');

-- --- 수집 노드 · 노드 점검 ---

CREATE TABLE server_snapshots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host         TEXT   NOT NULL,
    ip           TEXT   NOT NULL DEFAULT '',
    collected_at TEXT   NOT NULL,
    collected_by TEXT   NOT NULL DEFAULT '',
    file         TEXT   NOT NULL DEFAULT '',
    modules      TEXT   NOT NULL DEFAULT '{}',
    sections     TEXT   NOT NULL DEFAULT '{}',
    changes      TEXT   NOT NULL DEFAULT '[]',
    loaded_at    TEXT   NOT NULL,
    node         TEXT   NOT NULL DEFAULT '',
    UNIQUE (host, collected_at)
);
CREATE INDEX server_snapshots_latest ON server_snapshots (host, collected_at);
CREATE UNIQUE INDEX server_snapshots_node ON server_snapshots (node, collected_at) WHERE node <> '';
CREATE TRIGGER server_snapshots_immutable BEFORE UPDATE ON server_snapshots
    FOR EACH ROW EXECUTE FUNCTION deny('수집 기록은 고칠 수 없습니다');

CREATE TABLE node_findings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node        TEXT   NOT NULL,
    snapshot_id BIGINT NOT NULL REFERENCES server_snapshots (id),
    host        TEXT   NOT NULL DEFAULT '',
    ip          TEXT   NOT NULL DEFAULT '',
    state       TEXT   NOT NULL DEFAULT '{}',
    matched     TEXT   NOT NULL DEFAULT '',
    level       TEXT   CHECK (level IN ('정상', '주의', '위험')),
    summary     TEXT   NOT NULL DEFAULT '',
    gaps        TEXT   NOT NULL DEFAULT '[]',
    unjudged    TEXT   NOT NULL DEFAULT '[]',
    sources     TEXT   NOT NULL DEFAULT '[]',
    failed      INTEGER NOT NULL DEFAULT 0 CHECK (failed IN (0, 1)),
    error       TEXT,
    elapsed_sec DOUBLE PRECISION,
    model       TEXT   NOT NULL DEFAULT '',
    created_at  TEXT   NOT NULL,
    CHECK (failed = 1 OR level IS NOT NULL)
);
CREATE INDEX node_findings_node ON node_findings (node, id);
CREATE TRIGGER node_findings_immutable BEFORE UPDATE ON node_findings
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');

-- --- 사용자 위협 (의심 점수) ---

CREATE TABLE suspect_scores (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person      TEXT    NOT NULL,
    subject     TEXT    NOT NULL DEFAULT '',
    log_id      TEXT    NOT NULL DEFAULT '',
    login_id    TEXT,
    score       INTEGER CHECK (score BETWEEN 0 AND 100),
    level       TEXT    CHECK (level IN ('낮음', '보통', '높음')),
    reason      TEXT    NOT NULL DEFAULT '',
    watch       TEXT    NOT NULL DEFAULT '',
    signals     TEXT    NOT NULL DEFAULT '{}',
    records     TEXT    NOT NULL DEFAULT '{}',
    failed      INTEGER NOT NULL DEFAULT 0 CHECK (failed IN (0, 1)),
    error       TEXT,
    elapsed_sec DOUBLE PRECISION,
    model       TEXT    NOT NULL DEFAULT '',
    created_at  TEXT    NOT NULL,
    CHECK (failed = 1 OR (score IS NOT NULL AND level IS NOT NULL))
);
CREATE INDEX suspect_scores_person ON suspect_scores (person, id);
CREATE TRIGGER suspect_scores_immutable BEFORE UPDATE ON suspect_scores
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');
