-- results_grounding.sql 뒤에 적용 — AI 비서(보안 현황의 영역별 할 일)입니다. fingerprint = 그때 열린 것 · 결정 상태의 지문.
CREATE TABLE briefings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    headline    TEXT   NOT NULL DEFAULT '',
    areas       TEXT   NOT NULL DEFAULT '[]',
    fingerprint TEXT   NOT NULL DEFAULT '',
    failed      INTEGER NOT NULL DEFAULT 0 CHECK (failed IN (0, 1)),
    error       TEXT,
    model       TEXT   NOT NULL,
    elapsed_sec DOUBLE PRECISION,
    created_at  TEXT   NOT NULL,
    grounding   TEXT   NOT NULL DEFAULT '{}'
);
CREATE TRIGGER briefings_immutable BEFORE UPDATE ON briefings
    FOR EACH ROW EXECUTE FUNCTION deny('AI 결과는 고칠 수 없습니다');
