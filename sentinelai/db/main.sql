-- 권한 DB. 결재 순서 · 역할은 트리거가 강제하고, RAISE EXCEPTION 문장은 그대로 화면에 나갑니다.

CREATE FUNCTION deny() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0];
END $$;

-- --- 사용자 · 세션 · 감사 기록 ---

CREATE TABLE users (
    id                   BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id             TEXT    NOT NULL,
    password_hash        TEXT    NOT NULL,
    display_name         TEXT    NOT NULL,
    department           TEXT    NOT NULL DEFAULT '',
    role                 TEXT    NOT NULL CHECK (role IN ('top', 'manager', 'user')),
    is_root              INTEGER NOT NULL DEFAULT 0 CHECK (is_root IN (0, 1)),
    is_active            INTEGER NOT NULL DEFAULT 1,
    must_change_password INTEGER NOT NULL DEFAULT 1,
    failed_logins        INTEGER NOT NULL DEFAULT 0,
    locked_until         TEXT,
    password_changed_at  TEXT,
    last_login_at        TEXT,
    created_at           TEXT    NOT NULL,
    created_by           BIGINT  REFERENCES users (id),
    log_id               TEXT    NOT NULL DEFAULT '',
    job                  TEXT    NOT NULL DEFAULT '',
    left_on              TEXT    NOT NULL DEFAULT '',
    CHECK (is_root = 0 OR role = 'top'),
    CHECK (is_root = 1 OR created_by IS NOT NULL)
);
-- 로그인 ID 는 대소문자를 가리지 않으므로 lower() 에 유일 색인을 둡니다.
CREATE UNIQUE INDEX users_login_id ON users (lower(login_id));
CREATE UNIQUE INDEX users_single_root ON users (is_root) WHERE is_root = 1;
CREATE UNIQUE INDEX users_log_id ON users (log_id) WHERE log_id <> '';

CREATE FUNCTION users_created_by_top() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.created_by IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.created_by AND role = 'top' AND is_active = 1) THEN
        RAISE EXCEPTION '계정은 보안 총책임자만 만들 수 있습니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER users_created_by_top BEFORE INSERT ON users
    FOR EACH ROW EXECUTE FUNCTION users_created_by_top();

CREATE TABLE sessions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash   TEXT   NOT NULL UNIQUE,
    user_id      BIGINT NOT NULL REFERENCES users (id),
    created_at   TEXT   NOT NULL,
    last_seen_at TEXT   NOT NULL,
    expires_at   TEXT   NOT NULL,
    revoked_at   TEXT,
    ip           TEXT,
    user_agent   TEXT
);
CREATE INDEX sessions_user ON sessions (user_id);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TEXT   NOT NULL,
    user_id     BIGINT REFERENCES users (id),
    login_id    TEXT,
    action      TEXT   NOT NULL,
    target_type TEXT,
    target_id   TEXT,
    detail      TEXT   NOT NULL DEFAULT '{}',
    ip          TEXT
);
CREATE INDEX audit_log_at ON audit_log (at);
CREATE INDEX audit_log_user ON audit_log (user_id, at);

-- --- 권한 목록 ---

CREATE TABLE access_catalog (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        TEXT    NOT NULL UNIQUE CHECK (code ~ '^[A-Za-z0-9_.-]{1,64}$'),
    name        TEXT    NOT NULL CHECK (trim(name) <> ''),
    system      TEXT    NOT NULL DEFAULT '',
    category    TEXT    NOT NULL DEFAULT '',
    description TEXT    NOT NULL DEFAULT '',
    is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_by  BIGINT  NOT NULL REFERENCES users (id),
    created_at  TEXT    NOT NULL,
    updated_at  TEXT    NOT NULL
);

CREATE FUNCTION access_catalog_by_top() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.created_by AND role = 'top' AND is_active = 1) THEN
        RAISE EXCEPTION '권한 목록은 보안 총책임자만 관리할 수 있습니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER access_catalog_by_top BEFORE INSERT ON access_catalog
    FOR EACH ROW EXECUTE FUNCTION access_catalog_by_top();
CREATE TRIGGER access_catalog_code_frozen BEFORE UPDATE OF code ON access_catalog
    FOR EACH ROW EXECUTE FUNCTION deny('권한 코드는 바꿀 수 없습니다');
CREATE TRIGGER access_catalog_no_delete BEFORE DELETE ON access_catalog
    FOR EACH ROW EXECUTE FUNCTION deny('권한은 지우지 않고 끕니다');

-- --- 권한 신청 (1건 = 1행: 신청 · AI 판정 · 1차 · 최종 결재 · 회수) ---

CREATE TABLE access_requests (
    id                   BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- REQ-YYYYMMDD-NNN. 없는 날짜는 ::date 가 실패해 막힙니다.
    request_no           TEXT    NOT NULL UNIQUE
                                 CHECK (request_no ~ '^REQ-[0-9]{8}-[0-9]{3}$' AND substr(request_no, 5, 8)::date IS NOT NULL),
    requester_id         BIGINT  NOT NULL REFERENCES users (id),
    requester_name       TEXT    NOT NULL,
    requester_department TEXT    NOT NULL DEFAULT '',
    requested_access     TEXT    NOT NULL,
    current_access       TEXT    NOT NULL DEFAULT '',
    reason               TEXT    NOT NULL DEFAULT '',
    period_start         TEXT    NOT NULL DEFAULT '',
    period_end           TEXT    NOT NULL DEFAULT '',
    stage                TEXT    NOT NULL DEFAULT 'manager'
                                 CHECK (stage IN ('manager', 'top', 'approved', 'rejected', 'withdrawn', 'revoked')),
    submitted_at         TEXT    NOT NULL,
    closed_at            TEXT,

    ai_level             TEXT    CHECK (ai_level IN ('정상', '주의', '위험')),
    ai_reason            TEXT    NOT NULL DEFAULT '',
    ai_recommendation    TEXT    NOT NULL DEFAULT '',
    ai_sources           TEXT    NOT NULL DEFAULT '[]',
    ai_failed            INTEGER NOT NULL DEFAULT 0 CHECK (ai_failed IN (0, 1)),
    ai_error             TEXT,
    ai_model             TEXT,
    ai_elapsed_sec       DOUBLE PRECISION,
    ai_judged_at         TEXT,

    manager_action       TEXT    CHECK (manager_action IN ('approve', 'reject')),
    manager_comment      TEXT    NOT NULL DEFAULT '',
    manager_id           BIGINT  REFERENCES users (id),
    manager_name         TEXT,
    manager_department   TEXT,
    manager_decided_at   TEXT,

    top_action           TEXT    CHECK (top_action IN ('approve', 'reject')),
    top_comment          TEXT    NOT NULL DEFAULT '',
    top_id               BIGINT  REFERENCES users (id),
    top_name             TEXT,
    top_department       TEXT,
    top_decided_at       TEXT,

    revoke_reason        TEXT,
    revoker_id           BIGINT  REFERENCES users (id),
    revoker_name         TEXT,
    revoker_department   TEXT,
    revoked_at           TEXT,

    access_code          TEXT    REFERENCES access_catalog (code),
    requester_job        TEXT    NOT NULL DEFAULT '',

    CHECK (ai_judged_at IS NULL OR ai_failed = 1 OR ai_level IS NOT NULL),
    CHECK ((manager_action IS NULL) = (manager_id IS NULL) AND (manager_action IS NULL) = (manager_decided_at IS NULL)),
    CHECK ((top_action IS NULL) = (top_id IS NULL) AND (top_action IS NULL) = (top_decided_at IS NULL)),
    CHECK ((revoked_at IS NULL) = (revoker_id IS NULL) AND (revoked_at IS NULL) = (revoke_reason IS NULL)),
    CHECK (revoke_reason IS NULL OR trim(revoke_reason) <> ''),
    -- = 로 쓰면 NULL 이 통과하므로 IS NOT DISTINCT FROM 으로 씁니다.
    CHECK (top_action IS NULL OR manager_action IS NOT DISTINCT FROM 'approve'),
    CHECK (revoked_at IS NULL OR top_action IS NOT DISTINCT FROM 'approve')
);
CREATE INDEX access_requests_stage ON access_requests (stage, submitted_at);
CREATE INDEX access_requests_requester ON access_requests (requester_id, submitted_at);

CREATE FUNCTION access_requests_by_user() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.requester_id AND role = 'user' AND is_active = 1) THEN
        RAISE EXCEPTION '권한 신청은 일반 사용자만 할 수 있습니다';
    END IF;
    IF NEW.stage IS DISTINCT FROM 'manager' OR NEW.manager_action IS NOT NULL OR NEW.top_action IS NOT NULL
       OR NEW.revoked_at IS NOT NULL THEN
        RAISE EXCEPTION '신청은 결재 대기로만 넣을 수 있습니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER access_requests_by_user BEFORE INSERT ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_by_user();

CREATE FUNCTION access_requests_from_catalog() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM access_catalog WHERE code = NEW.access_code AND is_active = 1) THEN
        RAISE EXCEPTION '권한 목록에 있는 권한만 신청할 수 있습니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER access_requests_from_catalog BEFORE INSERT ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_from_catalog();

CREATE TRIGGER access_requests_fields_frozen
    BEFORE UPDATE OF request_no, requester_id, requester_name, requester_department, access_code,
                     requested_access, current_access, reason, period_start, period_end, submitted_at, requester_job
    ON access_requests
    FOR EACH ROW EXECUTE FUNCTION deny('제출한 신청 내용은 고칠 수 없습니다');

CREATE TRIGGER access_requests_no_delete BEFORE DELETE ON access_requests
    FOR EACH ROW EXECUTE FUNCTION deny('신청 기록은 지울 수 없습니다');

CREATE FUNCTION access_requests_ai_before_first_decision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.stage IS DISTINCT FROM 'manager' OR OLD.manager_action IS NOT NULL THEN
        RAISE EXCEPTION '1차 결재 뒤에는 AI 판정을 바꿀 수 없습니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER access_requests_ai_before_first_decision
    BEFORE UPDATE OF ai_level, ai_reason, ai_recommendation, ai_sources, ai_failed, ai_error, ai_model, ai_elapsed_sec, ai_judged_at
    ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_ai_before_first_decision();

CREATE FUNCTION access_requests_manager_step() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.manager_action IS NOT NULL THEN
        RAISE EXCEPTION '이미 결재한 단계입니다';
    END IF;
    IF OLD.stage IS DISTINCT FROM 'manager' THEN
        RAISE EXCEPTION '지금 결재 단계가 아닙니다';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.manager_id AND role = 'manager' AND is_active = 1) THEN
        RAISE EXCEPTION '이 단계를 결재할 역할이 아닙니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER access_requests_manager_step
    BEFORE UPDATE OF manager_action, manager_comment, manager_id, manager_name, manager_department, manager_decided_at
    ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_manager_step();

CREATE FUNCTION access_requests_top_step() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.top_action IS NOT NULL THEN
        RAISE EXCEPTION '이미 결재한 단계입니다';
    END IF;
    IF OLD.stage IS DISTINCT FROM 'top' THEN
        RAISE EXCEPTION '지금 결재 단계가 아닙니다';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.top_id AND role = 'top' AND is_active = 1) THEN
        RAISE EXCEPTION '이 단계를 결재할 역할이 아닙니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER access_requests_top_step
    BEFORE UPDATE OF top_action, top_comment, top_id, top_name, top_department, top_decided_at
    ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_top_step();

CREATE FUNCTION access_requests_revoke_step() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.revoked_at IS NOT NULL THEN
        RAISE EXCEPTION '이미 회수한 권한입니다';
    END IF;
    IF OLD.stage IS DISTINCT FROM 'approved' THEN
        RAISE EXCEPTION '승인된 권한만 회수할 수 있습니다';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.revoker_id AND role IN ('manager', 'top') AND is_active = 1) THEN
        RAISE EXCEPTION '권한 회수는 보안 운영자 · 보안 총책임자만 할 수 있습니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER access_requests_revoke_step
    BEFORE UPDATE OF revoke_reason, revoker_id, revoker_name, revoker_department, revoked_at
    ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_revoke_step();

-- 결재 · 회수 칸이 채워지면 단계를 옮깁니다. 이 UPDATE 도 access_requests_stage_path 를 거칩니다.
CREATE FUNCTION access_requests_manager_advance() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.manager_action IS NULL AND NEW.manager_action IS NOT NULL THEN
        UPDATE access_requests
        SET stage = CASE NEW.manager_action WHEN 'approve' THEN 'top' ELSE 'rejected' END,
            closed_at = CASE NEW.manager_action WHEN 'reject' THEN NEW.manager_decided_at END
        WHERE id = NEW.id;
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER access_requests_manager_advance AFTER UPDATE OF manager_action ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_manager_advance();

CREATE FUNCTION access_requests_top_advance() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.top_action IS NULL AND NEW.top_action IS NOT NULL THEN
        UPDATE access_requests
        SET stage = CASE NEW.top_action WHEN 'approve' THEN 'approved' ELSE 'rejected' END, closed_at = NEW.top_decided_at
        WHERE id = NEW.id;
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER access_requests_top_advance AFTER UPDATE OF top_action ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_top_advance();

CREATE FUNCTION access_requests_revoke_apply() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.revoked_at IS NULL AND NEW.revoked_at IS NOT NULL THEN
        UPDATE access_requests SET stage = 'revoked', closed_at = NEW.revoked_at WHERE id = NEW.id;
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER access_requests_revoke_apply AFTER UPDATE OF revoked_at ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_revoke_apply();

CREATE FUNCTION access_requests_stage_path() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.stage IS DISTINCT FROM OLD.stage
       AND NOT (   (OLD.stage = 'manager'  AND NEW.stage = 'top'       AND NEW.manager_action IS NOT DISTINCT FROM 'approve')
                OR (OLD.stage = 'manager'  AND NEW.stage = 'rejected'  AND NEW.manager_action IS NOT DISTINCT FROM 'reject')
                OR (OLD.stage = 'manager'  AND NEW.stage = 'withdrawn' AND NEW.manager_action IS NULL)
                OR (OLD.stage = 'top'      AND NEW.stage = 'approved'  AND NEW.top_action IS NOT DISTINCT FROM 'approve')
                OR (OLD.stage = 'top'      AND NEW.stage = 'rejected'  AND NEW.top_action IS NOT DISTINCT FROM 'reject')
                OR (OLD.stage = 'approved' AND NEW.stage = 'revoked'   AND NEW.revoked_at IS NOT NULL)) THEN
        RAISE EXCEPTION '허용되지 않은 상태 변경입니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER access_requests_stage_path BEFORE UPDATE OF stage ON access_requests
    FOR EACH ROW EXECUTE FUNCTION access_requests_stage_path();

CREATE VIEW active_grants AS
SELECT r.*
FROM access_requests r
WHERE r.stage = 'approved'
  AND (r.period_end = '' OR r.period_end >= to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD'));

-- --- 운영자 결정 (정책 관리 · 로그 감시 · 서버 점검) ---

CREATE TABLE review_decisions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind               TEXT   NOT NULL CHECK (kind IN ('policy', 'event', 'server')),
    item_key           TEXT   NOT NULL,
    subject            TEXT   NOT NULL DEFAULT '',
    action             TEXT   NOT NULL CHECK (
                           (kind = 'policy' AND action IN ('approve', 'cond', 'reject', 'cancel'))
                           OR (kind IN ('event', 'server') AND action IN ('clear', 'act', 'cancel'))),
    comment            TEXT   NOT NULL DEFAULT '',
    ai_level           TEXT   CHECK (ai_level IN ('정상', '주의', '위험')),
    decider_id         BIGINT NOT NULL REFERENCES users (id),
    decider_name       TEXT   NOT NULL,
    decider_department TEXT   NOT NULL DEFAULT '',
    decided_at         TEXT   NOT NULL
);
CREATE INDEX review_decisions_item ON review_decisions (kind, item_key, id);

CREATE FUNCTION review_decisions_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM users WHERE id = NEW.decider_id AND role IN ('manager', 'top') AND is_active = 1) THEN
        RAISE EXCEPTION '정책 · 로그 결정은 보안 운영자 · 보안 총책임자만 할 수 있습니다';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER review_decisions_check BEFORE INSERT ON review_decisions
    FOR EACH ROW EXECUTE FUNCTION review_decisions_check();
CREATE TRIGGER review_decisions_immutable_update BEFORE UPDATE ON review_decisions
    FOR EACH ROW EXECUTE FUNCTION deny('결정 기록은 고칠 수 없습니다');
CREATE TRIGGER review_decisions_immutable_delete BEFORE DELETE ON review_decisions
    FOR EACH ROW EXECUTE FUNCTION deny('결정 기록은 지울 수 없습니다');

